import { copyFileSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { basename, join } from 'node:path';

const sourceCssPath = 'node_modules/@fontsource/noto-serif-jp/400.css';
const sourceDirectory = 'node_modules/@fontsource/noto-serif-jp/files';
const outputDirectory = 'public/fonts/jp';
const sourceCss = readFileSync(sourceCssPath, 'utf8');
const siteText = readFileSync('index.html', 'utf8') + readFileSync('src/main.js', 'utf8');
const codepoints = new Set(
  [...siteText]
    .map((character) => character.codePointAt(0))
    .filter((codepoint) => codepoint >= 0x3000),
);

function parseRanges(value) {
  return value.split(',').map((part) => {
    const token = part.trim().replace(/^U\+/i, '');
    const [start, end = start] = token.split('-');
    return [Number.parseInt(start, 16), Number.parseInt(end, 16)];
  });
}

rmSync(outputDirectory, { recursive: true, force: true });
mkdirSync(outputDirectory, { recursive: true });

const usedBlocks = [];
for (const match of sourceCss.matchAll(/@font-face\s*\{[^}]+\}/g)) {
  const block = match[0];
  const rangeValue = block.match(/unicode-range:\s*([^;]+);/)?.[1];
  const sourceFile = block.match(/url\(\.\/files\/([^\)]+\.woff2)\)/)?.[1];
  if (!rangeValue || !sourceFile) continue;

  const ranges = parseRanges(rangeValue);
  const needed = [...codepoints].some((codepoint) =>
    ranges.some(([start, end]) => codepoint >= start && codepoint <= end));
  if (!needed) continue;

  copyFileSync(join(sourceDirectory, sourceFile), join(outputDirectory, sourceFile));
  usedBlocks.push(block.replace(
    /src:\s*url\(\.\/files\/[^\)]+\.woff2\) format\('woff2'\),\s*url\(\.\/files\/[^\)]+\.woff\) format\('woff'\);/,
    `src: url('/fonts/jp/${basename(sourceFile)}') format('woff2');`,
  ));
}

const header = '/* Generated by scripts/subset-jp-font.mjs — only glyph subsets used by the site. */\n';
writeFileSync('src/jp-font.css', header + usedBlocks.join('\n\n') + '\n');
console.log(`Copied ${usedBlocks.length} Japanese font subsets for ${codepoints.size} characters.`);
console.log(`Files: ${readdirSync(outputDirectory).join(', ')}`);
